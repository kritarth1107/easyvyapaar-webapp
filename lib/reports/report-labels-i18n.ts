export function translateReportLabel(label: string, locale: string): string {
  const map = (REPORT_LABELS as Record<string, Record<string, string>>)[locale];
  return map?.[label] ?? label;
}

export function localizeReportData(data: ReportData, locale: string): ReportData {
  if (!(locale in REPORT_LABELS)) return data;
  const tr = (s: string) => translateReportLabel(s, locale);
  const trOpt = (s?: string) => (s === undefined ? s : tr(s));
  const metrics = (items: ReportMetric[]) => items.map((m) => ({ ...m, label: tr(m.label) }));
  const cols = (c: ReportData["columns"]) => c.map((x) => ({ ...x, label: tr(x.label) }));
  const cell = (v: unknown) => (v === "Yes" || v === "No" ? tr(v) : v);
  const sections = data.sections.map((s): ReportSection => {
    switch (s.type) {
      case "metrics":
        return { ...s, title: trOpt(s.title), metrics: metrics(s.metrics) };
      case "info":
        return { ...s, title: trOpt(s.title), items: s.items.map((i) => ({ ...i, label: tr(i.label) })) };
      case "chart":
        return { ...s, chart: { ...s.chart, title: tr(s.chart.title), bars: s.chart.bars.map((b) => ({ ...b, label: tr(b.label) })) } };
      case "comparison":
        return {
          ...s,
          title: trOpt(s.title),
          left: { label: tr(s.left.label), items: metrics(s.left.items) },
          right: { label: tr(s.right.label), items: metrics(s.right.items) },
        };
      case "table":
        return {
          ...s,
          table: {
            ...s.table,
            title: tr(s.table.title),
            columns: cols(s.table.columns),
            rows: s.table.rows.map((r) => Object.fromEntries(Object.entries(r).map(([k, v]) => [k, cell(v)])) as typeof r),
            ...(s.table.footer
              ? { footer: Object.fromEntries(Object.entries(s.table.footer).map(([k, v]) => [k, typeof v === "string" ? tr(v) : v])) }
              : {}),
          },
        };
      default:
        return s;
    }
  });
  return { ...data, sections, columns: cols(data.columns) };
}
